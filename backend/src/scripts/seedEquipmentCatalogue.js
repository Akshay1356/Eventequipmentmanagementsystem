async function seed() {
  try {
    logger.info('Starting equipment catalogue seeding into MySQL...');

    let inserted = 0;
    let updated = 0;

    for (const item of equipmentData) {
      const [existing] = await pool.query('SELECT equipment_id FROM equipment WHERE sku = ?', [item.sku]);

      if (existing.length > 0) {
        await pool.query(
          `UPDATE equipment SET
            category_id = ?,
            equipment_name = ?,
            brand = ?,
            model = ?,
            short_desc = ?,
            description = ?,
            daily_rate = ?,
            replacement_value = ?,
            total_quantity = ?,
            condition_status = ?,
            listing_status = ?,
            image_url = ?,
            images = ?,
            specifications = ?,
            featured = ?,
            rating = ?
           WHERE sku = ?`,
          [
            item.category_id,
            item.equipment_name,
            item.brand,
            item.model,
            item.short_desc,
            item.description,
            item.daily_rate,
            item.replacement_value,
            item.total_quantity,
            item.condition_status,
            item.listing_status,
            item.image_url,
            JSON.stringify([item.image_url]),
            JSON.stringify(item.specifications),
            item.featured,
            item.rating,
            item.sku
          ]
        );
        updated++;
      } else {
        await pool.query(
          `INSERT INTO equipment (
            equipment_id, category_id, sku, equipment_name, brand, model,
            short_desc, description, daily_rate, replacement_value, total_quantity,
            condition_status, listing_status, image_url, images, specifications,
            featured, rating
          ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          [
            item.id,
            item.category_id,
            item.sku,
            item.equipment_name,
            item.brand,
            item.model,
            item.short_desc,
            item.description,
            item.daily_rate,
            item.replacement_value,
            item.total_quantity,
            item.condition_status,
            item.listing_status,
            item.image_url,
            JSON.stringify([item.image_url]),
            JSON.stringify(item.specifications),
            item.featured,
            item.rating
          ]
        );
        inserted++;
      }
    }

    logger.info(`Seeding complete: ${inserted} items inserted, ${updated} items updated.`);
    return { inserted, updated };
  } catch (error) {
    logger.error('Seeding failed:', error.message);
    throw error;
  }
}

